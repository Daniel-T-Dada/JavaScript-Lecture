/*
ARRRAY: An array is a data structure that can hold multiple values at once. It is a collection of elements, where each element can be of any data type (such as numbers, strings, or even other arrays). Arrays are ordered, meaning that the elements are stored in a specific sequence and can be accessed using their index (position) in the array.

*/

// Creating an array
let fruits = ["Apple", "Banana", "Cherry", "Date", "Elderberry"];

// Accessing elements in an array
const getBanana = fruits[1]; // Accessing the second element (index starts at 0)
console.log(getBanana); // Output: "Banana"

fruits[2] = "Pear"; // Modifying the third element
console.log(fruits); // Output: ["Apple", "Banana", "Pear", "Date", "Elderberry"]

